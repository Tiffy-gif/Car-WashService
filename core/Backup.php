class Backup {

    public static function getBackupDir(): string {
        $dir = dirname(__DIR__) . '/storage/backups';
        if (!is_dir($dir)) {
            @mkdir($dir, 0750, true);
        }
        return $dir;
    }

    /**
     * Dynamically generates a complete, self-contained SQL dump of all database tables.
     */
    public static function generateSql(PDO $pdo): string {
        // Dynamically find all base tables in the current active database
        $tables = [];
        $driver = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);

        if ($driver === 'mysql') {
            $tStmt = $pdo->query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'");
            while ($r = $tStmt->fetch(PDO::FETCH_NUM)) {
                $tables[] = $r[0];
            }
        } elseif ($driver === 'sqlite') {
            $tStmt = $pdo->query("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'");
            while ($r = $tStmt->fetch(PDO::FETCH_NUM)) {
                $tables[] = $r[0];
            }
        }

        if (empty($tables)) {
            $tables = [
                'settings', 'users', 'roles', 'permissions', 'role_permissions', 'role_audit_logs',
                'categories', 'services', 'service_prices', 'customers', 'vehicles', 'orders',
                'order_items', 'order_washers', 'order_mechanics', 'order_tasks', 'task_checklists',
                'parts_requests', 'expenses', 'products', 'inventory', 'stock_movements',
                'stock_discrepancies', 'bays', 'bay_history', 'cashier_shifts', 'spot_audits',
                'drawer_events', 'pos_devices', 'pos_closings', 'staff_timecards', 'timecard_corrections',
                'loyalty_transactions', 'system_notifications', 'sync_queue', 'sync_conflicts',
                'sync_logs', 'audit_logs', 'schema_migrations'
            ];
        }

        $now = date('Y-m-d H:i:s');
        $userStr = (class_exists('Auth') && Auth::isLoggedIn()) ? (Auth::getFullName() . " (@" . Auth::getUsername() . ")") : "System Automated Job (2:00 AM)";

        $dump = "-- ========================================================\n";
        $dump .= "-- AquaGleam Car Wash & Detailing - Full Database Backup\n";
        $dump .= "-- Generated: {$now}\n";
        $dump .= "-- Generated by: {$userStr}\n";
        $dump .= "-- ========================================================\n\n";
        $dump .= "SET FOREIGN_KEY_CHECKS=0;\n";
        $dump .= "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n";
        $dump .= "SET NAMES utf8mb4;\n\n";

        foreach ($tables as $table) {
            try {
                $dump .= "-- --------------------------------------------------------\n";
                $dump .= "-- Structure for table `{$table}`\n";
                $dump .= "-- --------------------------------------------------------\n";
                $dump .= "DROP TABLE IF EXISTS `{$table}`;\n";

                if ($driver === 'mysql') {
                    $createStmt = $pdo->query("SHOW CREATE TABLE `{$table}`")->fetch(PDO::FETCH_ASSOC);
                    $createSql = $createStmt['Create Table'] ?? '';
                    $dump .= $createSql . ";\n\n";
                } elseif ($driver === 'sqlite') {
                    $tStmt = $pdo->prepare("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?");
                    $tStmt->execute([$table]);
                    $createSql = (string)$tStmt->fetchColumn();
                    if (!empty($createSql)) {
                        $dump .= $createSql . ";\n\n";
                    }
                }

                // Dump Data
                $rows = $pdo->query("SELECT * FROM `{$table}`")->fetchAll(PDO::FETCH_ASSOC);
                if (!empty($rows)) {
                    $dump .= "-- Data for table `{$table}` (" . count($rows) . " rows)\n";
                    $cols = array_keys($rows[0]);
                    $colsEscaped = implode('`, `', $cols);

                    foreach ($rows as $row) {
                        $values = [];
                        foreach ($row as $val) {
                            if ($val === null) {
                                $values[] = 'NULL';
                            } else {
                                $values[] = $pdo->quote((string)$val);
                            }
                        }
                        $dump .= "INSERT INTO `{$table}` (`{$colsEscaped}`) VALUES (" . implode(', ', $values) . ");\n";
                    }
                    $dump .= "\n";
                }
            } catch (Exception $e) {
                $dump .= "-- Could not dump table `{$table}`: " . $e->getMessage() . "\n\n";
            }
        }

        // Dump Triggers (to ensure self-contained, reproducible backups)
        if ($driver === 'mysql') {
            try {
                $trigStmt = $pdo->query("SHOW TRIGGERS");
                $triggers = $trigStmt ? $trigStmt->fetchAll(PDO::FETCH_ASSOC) : [];
                if (!empty($triggers)) {
                    $dump .= "-- --------------------------------------------------------\n";
                    $dump .= "-- Triggers structure\n";
                    $dump .= "-- --------------------------------------------------------\n";
                    foreach ($triggers as $t) {
                        $trgName = $t['Trigger'];
                        $createStmt = $pdo->query("SHOW CREATE TRIGGER `{$trgName}`")->fetch(PDO::FETCH_ASSOC);
                        $createSql = $createStmt['SQL Original Statement'] ?? '';
                        if (!empty($createSql)) {
                            $dump .= "DROP TRIGGER IF EXISTS `{$trgName}`;\n";
                            $dump .= "DELIMITER ;;\n";
                            $dump .= $createSql . ";;\n";
                            $dump .= "DELIMITER ;\n\n";
                        }
                    }
                }
            } catch (Throwable $e) {
                $dump .= "-- Could not dump triggers: " . $e->getMessage() . "\n\n";
            }
        } elseif ($driver === 'sqlite') {
            try {
                $trigStmt = $pdo->query("SELECT name, sql FROM sqlite_master WHERE type = 'trigger' AND name NOT LIKE 'sqlite_%'");
                $triggers = $trigStmt ? $trigStmt->fetchAll(PDO::FETCH_ASSOC) : [];
                if (!empty($triggers)) {
                    $dump .= "-- --------------------------------------------------------\n";
                    $dump .= "-- Triggers structure\n";
                    $dump .= "-- --------------------------------------------------------\n";
                    foreach ($triggers as $t) {
                        $trgName = $t['name'];
                        $createSql = $t['sql'];
                        if (!empty($createSql)) {
                            $dump .= "DROP TRIGGER IF EXISTS `{$trgName}`;\n";
                            $dump .= $createSql . ";\n\n";
                        }
                    }
                }
            } catch (Throwable $e) {
                $dump .= "-- Could not dump triggers: " . $e->getMessage() . "\n\n";
            }
        }

        $dump .= "SET FOREIGN_KEY_CHECKS=1;\n";
        $dump .= "-- [End of Database Backup]\n";

        return $dump;
    }

    /**
     * Executes the daily automated 2:00 AM backup and prunes files older than 14 days.
     */
    public static function runDailyBackup(PDO $pdo, ?string $targetDir = null, int $keepDays = 14): array {
        $targetDir = $targetDir ?: self::getBackupDir();
        $dateStr = date('Y-m-d');
        $filename = "CarWash_AutoBackup_{$dateStr}.sql";
        $filePath = rtrim($targetDir, '/\\') . DIRECTORY_SEPARATOR . $filename;

        $sqlContent = self::generateSql($pdo);
        $bytesWritten = file_put_contents($filePath, $sqlContent, LOCK_EX);

        if ($bytesWritten === false) {
            throw new RuntimeException("Failed to write daily backup to {$filePath}");
        }

        // Prune backups older than $keepDays
        $pruned = self::rotateBackups($targetDir, $keepDays);

        $logMsg = sprintf(
            "[%s] Automated daily backup created: %s (%s KB). Rotated: %d old backups removed.\n",
            date('Y-m-d H:i:s'),
            $filename,
            number_format($bytesWritten / 1024, 2),
            count($pruned)
        );

        @file_put_contents(dirname(__DIR__) . '/storage/logs/backup.log', $logMsg, FILE_APPEND | LOCK_EX);
        AuditLogger::log('BACKUP_AUTOMATIC', "Daily automated database backup saved: {$filename} (" . round($bytesWritten / 1024) . " KB)", 'system', $filename);

        return [
            'success' => true,
            'filename' => $filename,
            'file_path' => $filePath,
            'size_bytes' => $bytesWritten,
            'size_kb' => round($bytesWritten / 1024, 2),
            'pruned_files' => $pruned
        ];
    }

    /**
     * Removes backup files older than $keepDays (default: 14 days).
     */
    public static function rotateBackups(string $targetDir, int $keepDays = 14): array {
        $pruned = [];
        $cutoffTime = time() - ($keepDays * 86400);

        if (!is_dir($targetDir)) return $pruned;

        $files = scandir($targetDir) ?: [];
        foreach ($files as $file) {
            if ($file === '.' || $file === '..' || !str_ends_with($file, '.sql')) continue;

            $fullPath = rtrim($targetDir, '/\\') . DIRECTORY_SEPARATOR . $file;
            if (!is_file($fullPath)) continue;

            $mtime = filemtime($fullPath);
            $isOld = ($mtime < $cutoffTime);

            // Also check date in filename if available (e.g., CarWash_AutoBackup_2025-01-01.sql)
            if (preg_match('/CarWash_AutoBackup_(\d{4}-\d{2}-\d{2})\.sql/', $file, $m)) {
                $fileDateTs = strtotime($m[1]);
                if ($fileDateTs && $fileDateTs < $cutoffTime) {
                    $isOld = true;
                }
            }

            if ($isOld) {
                if (@unlink($fullPath)) {
                    $pruned[] = $file;
                }
            }
        }

        return $pruned;
    }

    /**
     * Returns list of existing backup files in storage/backups/
     */
    public static function getAvailableBackups(?string $targetDir = null): array {
        $targetDir = $targetDir ?: self::getBackupDir();
        $list = [];

        if (!is_dir($targetDir)) return $list;

        $files = scandir($targetDir) ?: [];
        foreach ($files as $file) {
            if ($file === '.' || $file === '..' || !str_ends_with($file, '.sql')) continue;

            $fullPath = rtrim($targetDir, '/\\') . DIRECTORY_SEPARATOR . $file;
            if (!is_file($fullPath)) continue;

            $size = filesize($fullPath);
            $mtime = filemtime($fullPath);

            $list[] = [
                'filename' => $file,
                'path' => $fullPath,
                'size_bytes' => $size,
                'size_formatted' => ($size > 1048576) ? number_format($size / 1048576, 2) . ' MB' : number_format($size / 1024, 1) . ' KB',
                'created_at' => date('Y-m-d H:i:s', $mtime),
                'age_days' => round((time() - $mtime) / 86400, 1),
                'is_auto' => str_starts_with($file, 'CarWash_AutoBackup_')
            ];
        }

        // Sort latest first
        usort($list, fn($a, $b) => strcmp($b['created_at'], $a['created_at']));
        return $list;
    }

    /**
     * Restores the database from a given SQL dump string.
     * Automatically reinstalls and catalog-verifies all four mandatory immutable ledger triggers.
     * If trigger verification fails, restore reports failure and flags the unprotected state.
     */
    public static function restoreFromSql(PDO $pdo, string $sqlContent): array {
        if (!str_contains($sqlContent, 'Car Wash') && !str_contains($sqlContent, 'SET FOREIGN_KEY_CHECKS')) {
            throw new InvalidArgumentException("Uploaded file is not a valid Car Wash Service Pro SQL backup dump.");
        }

        $lines = explode("\n", $sqlContent);
        $currentQuery = '';
        $executedCount = 0;
        $inBeginBlock = false;

        $driver = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);
        if ($driver === 'mysql') {
            $pdo->exec("SET FOREIGN_KEY_CHECKS=0;");
        } else {
            $pdo->exec("PRAGMA foreign_keys = OFF;");
        }

        foreach ($lines as $line) {
            $trimmed = trim($line);
            // Skip comments, empty lines, and client-only commands like DELIMITER
            if ($trimmed === '' || str_starts_with($trimmed, '--') || str_starts_with($trimmed, '/*') || stripos($trimmed, 'DELIMITER ') === 0) {
                continue;
            }

            // Track multi-statement trigger BEGIN...END blocks
            if (preg_match('/\bBEGIN\b/i', $trimmed)) {
                $inBeginBlock = true;
            }

            $currentQuery .= $line . "\n";

            $isEndOfStatement = false;
            if ($inBeginBlock) {
                if (preg_match('/\bEND\s*;;/i', $trimmed) || preg_match('/\bEND\s*;/i', $trimmed)) {
                    $isEndOfStatement = true;
                    $inBeginBlock = false;
                }
            } elseif (str_ends_with($trimmed, ';') || str_ends_with($trimmed, ';;')) {
                $isEndOfStatement = true;
            }

            if ($isEndOfStatement) {
                $queryToExec = trim($currentQuery);
                // Strip delimiter semicolons if doubled
                if (str_ends_with($queryToExec, ';;')) {
                    $queryToExec = substr($queryToExec, 0, -2);
                }

                if ($queryToExec !== '') {
                    // Skip MySQL session commands when restoring on SQLite
                    if ($driver === 'sqlite' && stripos($queryToExec, 'SET ') === 0) {
                        $currentQuery = '';
                        continue;
                    }

                    try {
                        $pdo->exec($queryToExec);
                        $executedCount++;
                    } catch (Throwable $t) {
                        // Ignore non-fatal drop errors if table or trigger doesn't exist
                        if (!str_contains($queryToExec, 'DROP TABLE') && !str_contains($queryToExec, 'DROP TRIGGER')) {
                            throw $t;
                        }
                    }
                }
                $currentQuery = '';
            }
        }

        if ($driver === 'mysql') {
            $pdo->exec("SET FOREIGN_KEY_CHECKS=1;");
        } else {
            $pdo->exec("PRAGMA foreign_keys = ON;");
        }

        // Automatic post-restore trigger installation & physical catalog verification
        require_once dirname(__DIR__) . '/database/migrate_immutable_ledgers.php';
        $triggerInstalled = migrateImmutableLedgers(true, $pdo);
        $verification = verifyImmutableTriggers($pdo);

        if (!$triggerInstalled || !$verification['valid']) {
            $errList = !empty($verification['errors']) ? implode('; ', $verification['errors']) : 'Trigger installation failed';
            
            if (class_exists('AuditLogger')) {
                AuditLogger::log('BACKUP_RESTORE_UNPROTECTED', "Database restored from dump ({$executedCount} statements) but immutable triggers could not be secured: {$errList}", 'system');
            }

            return [
                'success' => false,
                'statements_executed' => $executedCount,
                'triggers_verified' => false,
                'error' => "Database restored in an UNPROTECTED state: {$errList}",
                'message' => "RESTORE FAILED TO SECURE DATABASE: All data statements executed, but immutable ledger triggers could not be verified in the catalog ({$errList}). Protected operations refused."
            ];
        }

        if (class_exists('AuditLogger')) {
            AuditLogger::log('BACKUP_RESTORED', "Database restored from backup dump ({$executedCount} statements executed, 4 immutable triggers verified)", 'system');
        }

        return [
            'success' => true,
            'statements_executed' => $executedCount,
            'triggers_verified' => true,
            'message' => "Database restored successfully ({$executedCount} statements executed) and immutable ledger triggers verified."
        ];
    }

    public static function downloadSqlBackup(PDO $pdo): void {
        if (class_exists('Auth')) {
            Auth::requirePermission('backup.manage');
        }

        $filename = 'CarWash_Backup_' . date('Y-m-d_His') . '.sql';
        $dump = self::generateSql($pdo);

        if (class_exists('AuditLogger')) {
            AuditLogger::log('BACKUP_DOWNLOAD', "Owner downloaded live database backup: {$filename}", 'system', $filename);
        }

        header('Content-Type: application/sql; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Content-Length: ' . strlen($dump));
        header('Cache-Control: no-cache, no-store, must-revalidate');
        header('Pragma: no-cache');
        header('Expires: 0');

        echo $dump;
        exit;
    }
}
