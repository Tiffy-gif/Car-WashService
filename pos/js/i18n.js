class I18nManager {
    static getLang() {
        return PosStorage.getLanguage();
    }

    static setLang(lang) {
        PosStorage.setLanguage(lang);
        document.documentElement.lang = lang;
        this.applyToDOM();
    }

    static t(key) {
        const lang = this.getLang();
        return I18N[lang]?.[key] || I18N['en']?.[key] || key;
    }

    static applyToDOM() {
        const lang = this.getLang() || 'km';
        document.documentElement.lang = lang;

        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                el.placeholder = translation;
            } else {
                el.textContent = translation;
            }
            if (el.parentElement && el.parentElement.classList.contains('nav-tab')) {
                el.parentElement.title = translation;
            }
        });

        const titleElements = document.querySelectorAll('[data-i18n-title]');
        titleElements.forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            el.title = this.t(key);
        });

        const langBtn = document.getElementById('btnLangToggle');
        if (langBtn) {
            langBtn.textContent = lang === 'km' ? 'EN' : 'ខ្មែរ';
        }

        const segKm = document.getElementById('btnLangKm');
        const segEn = document.getElementById('btnLangEn');
        if (segKm && segEn) {
            segKm.classList.toggle('active', lang === 'km');
            segEn.classList.toggle('active', lang === 'en');
        }

        const shiftStatusEl = document.getElementById('topbarShiftStatusText');
        if (shiftStatusEl) {
            shiftStatusEl.textContent = this.t('shiftOpen');
        }

        const custNameEl = document.getElementById('topbarCustomerName');
        if (custNameEl && (!window.PosApp || !window.PosApp.currentCustomer)) {
            custNameEl.textContent = this.t('generalCustomer');
        }
    }
}

window.I18nManager = I18nManager;
